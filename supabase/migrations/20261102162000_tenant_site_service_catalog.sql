create or replace function public.tenant_site_service_catalog_snapshot(p_tenant_id uuid)
returns jsonb language plpgsql stable security definer
set search_path=public,auth as $$
declare v_result jsonb;
begin
  if auth.uid() is null or not exists (
    select 1 from jsonb_array_elements(public.current_site_activity_contexts()) c
    where c->>'tenant_id'=p_tenant_id::text
      and coalesce(c->>'authorization_role','') not in ('member','customer')
  ) then raise exception 'tenant_site_access_required' using errcode='42501'; end if;
  select jsonb_build_object('tenantId',p_tenant_id,'items',coalesce(jsonb_agg(
    jsonb_build_object('key',c.service_key,'category',c.category_key,
      'categoryLabel',c.category_label,'label',c.label,'description',c.description,
      'readiness',c.readiness,'navSection',c.nav_section,'risk',c.risk_level,
      'menuVisible',coalesce(p.menu_visible,true))
    order by c.sort_order), '[]'::jsonb))
    into v_result
    from public.tenant_site_service_catalog c
    left join public.tenant_site_service_preferences p on p.service_key=c.service_key and p.tenant_id=p_tenant_id;
  return v_result;
end $$;

create or replace function public.tenant_site_service_preference_set(
 p_tenant_id uuid,p_service_key text,p_menu_visible boolean)
returns jsonb language plpgsql volatile security definer
set search_path=public,auth as $$
declare v_previous boolean;v_ready text;
begin
  if auth.uid() is null or p_menu_visible is null or not exists (
    select 1 from jsonb_array_elements(public.current_site_activity_contexts()) c
    where c->>'tenant_id'=p_tenant_id::text and c->>'authorization_role'
      in ('tenant_admin','store_owner','owner','admin','client_admin','senior_pastor','workspace_admin')
  ) then raise exception 'tenant_site_admin_required' using errcode='42501'; end if;
  select readiness into v_ready from public.tenant_site_service_catalog where service_key=p_service_key;
  if v_ready is distinct from 'ready' then raise exception 'service_not_ready_for_menu_selection' using errcode='22023'; end if;
  select menu_visible into v_previous from public.tenant_site_service_preferences
    where tenant_id=p_tenant_id and service_key=p_service_key for update;
  if coalesce(v_previous,true) is distinct from p_menu_visible then
    insert into public.tenant_site_service_preferences(tenant_id,service_key,menu_visible,updated_by,updated_at)
      values(p_tenant_id,p_service_key,p_menu_visible,auth.uid(),now())
    on conflict (tenant_id,service_key) do update set
      menu_visible=excluded.menu_visible,updated_by=excluded.updated_by,updated_at=now();
    insert into public.tenant_site_service_audit(tenant_id,service_key,old_visible,new_visible,actor_id)
      values(p_tenant_id,p_service_key,coalesce(v_previous,true),p_menu_visible,auth.uid());
  end if;
  return public.tenant_site_service_catalog_snapshot(p_tenant_id);
end $$;

revoke all on function public.tenant_site_service_catalog_snapshot(uuid) from public,anon;
revoke all on function public.tenant_site_service_preference_set(uuid,text,boolean) from public,anon;
grant execute on function public.tenant_site_service_catalog_snapshot(uuid) to authenticated;
grant execute on function public.tenant_site_service_preference_set(uuid,text,boolean) to authenticated;
comment on table public.tenant_site_service_preferences is 'Menu visibility preferences only; does not grant capabilities or activate external side effects.';
