-- Tenant-owned service menu composition. Never confers operational authorization.
-- A visible menu does not enable payments, broadcast, publication or an external integration.
create table if not exists public.tenant_site_service_catalog (
  service_key text primary key check (service_key ~ '^[a-z][a-z0-9_-]{1,48}$'),
  category_key text not null,
  category_label text not null,
  label text not null,
  description text not null default '',
  readiness text not null check (readiness in ('ready','setup_required','planned')),
  nav_section text,
  sort_order integer not null default 100,
  risk_level text not null default 'normal' check (risk_level in ('normal','high'))
);
create table if not exists public.tenant_site_service_preferences (
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  service_key text not null references public.tenant_site_service_catalog(service_key),
  menu_visible boolean not null default true,
  updated_by uuid,
  updated_at timestamptz not null default now(),
  primary key (tenant_id,service_key)
);
create table if not exists public.tenant_site_service_audit (
  id bigint generated by default as identity primary key,
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  service_key text not null,
  old_visible boolean,
  new_visible boolean not null,
  actor_id uuid not null,
  created_at timestamptz not null default now()
);
create index if not exists tenant_site_service_audit_tenant_time
  on public.tenant_site_service_audit(tenant_id,created_at desc);
alter table public.tenant_site_service_catalog enable row level security;
alter table public.tenant_site_service_preferences enable row level security;
alter table public.tenant_site_service_audit enable row level security;
revoke all on public.tenant_site_service_catalog,public.tenant_site_service_preferences,public.tenant_site_service_audit from anon,authenticated,service_role;
revoke all on sequence public.tenant_site_service_audit_id_seq from anon,authenticated,service_role;

