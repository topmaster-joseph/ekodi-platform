create table if not exists public.tenant_ai_tool_preferences (
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  tool_id text not null references public.tenant_ai_tool_catalog(tool_id),
  selected boolean not null default false,
  updated_by uuid not null,
  updated_at timestamptz not null default now(),
  primary key (tenant_id,tool_id)
);

create table if not exists public.tenant_ai_tool_audit (
  id bigint generated by default as identity primary key,
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  tool_id text not null references public.tenant_ai_tool_catalog(tool_id),
  previous_selected boolean not null,
  next_selected boolean not null,
  actor_id uuid not null,
  created_at timestamptz not null default now()
);
create index if not exists tenant_ai_tool_audit_tenant_time
  on public.tenant_ai_tool_audit(tenant_id,created_at desc);

