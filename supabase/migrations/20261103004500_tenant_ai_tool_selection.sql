-- EKODI AI tool discovery and site-owned candidate selection.
-- This catalog is NOT an execution entitlement, connection proof or paid API approval.
-- It reuses tenant identity and role truth from current_site_activity_contexts().
create table if not exists public.tenant_ai_tool_catalog (
  tool_id text primary key check (tool_id ~ '^[a-z][a-z0-9_-]{1,48}$'),
  tool_name text not null,
  category text not null,
  connection_mode text not null check (connection_mode in ('existing-provider','external-reference')),
  provider_id text,
  website text not null check (website ~ '^https://'),
  sort_order integer not null default 100
);

