create or replace function public.tenant_ai_tool_catalog_snapshot(p_tenant_id uuid)
returns jsonb language plpgsql stable security definer
set search_path = '' as $$
declare v_result jsonb;
begin
  if auth.uid() is null or p_tenant_id is null or not exists (
    select 1 from pg_catalog.jsonb_array_elements(public.current_site_activity_contexts()) c
    where c->>'tenant_id'=p_tenant_id::text
      and c->>'authorization_role' in (
        'tenant_admin','store_owner','owner','admin','client_admin',
        'senior_pastor','workspace_admin'
      )
  ) then
    raise exception 'tenant_ai_tool_admin_required' using errcode='42501';
  end if;

  select pg_catalog.jsonb_build_object(
    'tenantId',p_tenant_id,
    'selectionOnly',true,
    'tools',coalesce(pg_catalog.jsonb_agg(
      pg_catalog.jsonb_build_object(
        'id',c.tool_id,'name',c.tool_name,'category',c.category,
        'connectionMode',c.connection_mode,'providerId',c.provider_id,
        'website',c.website,'selected',coalesce(p.selected,false)
      ) order by c.sort_order), '[]'::jsonb)
  ) into v_result
  from public.tenant_ai_tool_catalog c
  left join public.tenant_ai_tool_preferences p
    on p.tenant_id=p_tenant_id and p.tool_id=c.tool_id;
  return v_result;
end $$;

create or replace function public.tenant_ai_tool_preference_set(
  p_tenant_id uuid,p_tool_id text,p_selected boolean
)
returns jsonb language plpgsql volatile security definer
set search_path = '' as $$
declare v_previous boolean;v_exists boolean;
begin
  if auth.uid() is null or p_tenant_id is null or p_selected is null
    or not exists (
      select 1 from pg_catalog.jsonb_array_elements(public.current_site_activity_contexts()) c
      where c->>'tenant_id'=p_tenant_id::text
        and c->>'authorization_role' in (
          'tenant_admin','store_owner','owner','admin','client_admin',
          'senior_pastor','workspace_admin'
        )
    )
  then raise exception 'tenant_ai_tool_admin_required' using errcode='42501'; end if;

  select exists(select 1 from public.tenant_ai_tool_catalog where tool_id=p_tool_id)
    into v_exists;
  if not v_exists then raise exception 'unknown_ai_tool' using errcode='22023'; end if;

  select selected into v_previous from public.tenant_ai_tool_preferences
    where tenant_id=p_tenant_id and tool_id=p_tool_id for update;
  if coalesce(v_previous,false) is distinct from p_selected then
    insert into public.tenant_ai_tool_preferences
      (tenant_id,tool_id,selected,updated_by,updated_at)
    values (p_tenant_id,p_tool_id,p_selected,auth.uid(),now())
    on conflict (tenant_id,tool_id) do update set
      selected=excluded.selected,updated_by=excluded.updated_by,updated_at=now();
    insert into public.tenant_ai_tool_audit
      (tenant_id,tool_id,previous_selected,next_selected,actor_id)
    values (p_tenant_id,p_tool_id,coalesce(v_previous,false),p_selected,auth.uid());
  end if;

  return public.tenant_ai_tool_catalog_snapshot(p_tenant_id);
end $$;

revoke all on function public.tenant_ai_tool_catalog_snapshot(uuid) from public,anon,authenticated,service_role;
revoke all on function public.tenant_ai_tool_preference_set(uuid,text,boolean) from public,anon,authenticated,service_role;
grant execute on function public.tenant_ai_tool_catalog_snapshot(uuid) to authenticated;
grant execute on function public.tenant_ai_tool_preference_set(uuid,text,boolean) to authenticated;
