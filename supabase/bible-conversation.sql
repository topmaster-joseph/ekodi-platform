create or replace function public.bible_is_group_member(p_group_id uuid)
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.bible_group_members gm where gm.group_id=p_group_id and gm.user_id=auth.uid()) $$;

create or replace function public.bible_create_group(p_name text, p_kind text default 'small_group', p_tenant_slug text default 'ekodi-church')
returns public.bible_groups language plpgsql security definer set search_path=public
as $$
declare g public.bible_groups;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  insert into public.bible_groups(owner_id,name,kind,tenant_slug)
  values(auth.uid(),left(trim(p_name),120),coalesce(nullif(p_kind,''),'small_group'),coalesce(nullif(p_tenant_slug,''),'ekodi-church'))
  returning * into g;
  insert into public.bible_group_members(group_id,user_id,role) values(g.id,auth.uid(),'owner') on conflict do nothing;
  return g;
end $$;

create or replace function public.bible_join_group(p_invite_code text)
returns uuid language plpgsql security definer set search_path=public
as $$
declare gid uuid;
begin
  if auth.uid() is null then raise exception 'AUTH_REQUIRED'; end if;
  select id into gid from public.bible_groups where invite_code=upper(trim(p_invite_code));
  if gid is null then raise exception 'INVITE_NOT_FOUND'; end if;
  insert into public.bible_group_members(group_id,user_id,role) values(gid,auth.uid(),'member') on conflict do nothing;
  return gid;
end $$;

create or replace function public.bible_shared_feed(p_limit integer default 50)
returns table(share_id uuid,group_id uuid,journey_id uuid,owner_id uuid,title text,topic text,scripture_ref text,reflection text,note text,shared_at timestamptz)
language sql stable security definer set search_path=public
as $$
  select s.id,s.group_id,s.journey_id,s.user_id,j.title,j.topic,j.scripture_ref,j.reflection,s.note,s.created_at
  from public.bible_shared_journeys s
  join public.bible_journeys j on j.id=s.journey_id and j.user_id=s.user_id
  where auth.uid() is not null
    and exists(select 1 from public.bible_group_members gm where gm.group_id=s.group_id and gm.user_id=auth.uid())
  order by s.created_at desc
  limit least(greatest(coalesce(p_limit,50),1),100)
$$;

revoke all on function public.bible_is_group_member(uuid) from public, anon;
revoke all on function public.bible_create_group(text,text,text) from public, anon;
revoke all on function public.bible_join_group(text) from public, anon;
revoke all on function public.bible_shared_feed(integer) from public, anon;
grant execute on function public.bible_is_group_member(uuid) to authenticated;
grant execute on function public.bible_create_group(text,text,text) to authenticated;
grant execute on function public.bible_join_group(text) to authenticated;
grant execute on function public.bible_shared_feed(integer) to authenticated;

