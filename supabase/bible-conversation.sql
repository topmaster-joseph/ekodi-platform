-- EKODI Bible Conversation database contract
-- Namespace: public.bible_*
-- Privacy default: owner-only; community sharing is explicit.

create table if not exists public.bible_journeys (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  tenant_slug text not null default 'ekodi-church',
  topic text not null,
  title text not null,
  scripture_ref text not null default '',
  reflection text not null default '',
  prayer text not null default '',
  status text not null default 'open' check (status in ('open','practicing','completed','archived')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.bible_conversations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  journey_id uuid references public.bible_journeys(id) on delete set null,
  tenant_slug text not null default 'ekodi-church',
  topic text not null default '삶',
  mode text not null default 'guided' check (mode in ('guided','ai','free_assist')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.bible_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.bible_conversations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('user','assistant','system')),
  content text not null check (char_length(content) between 1 and 8000),
  scripture_ref text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.bible_practices (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  journey_id uuid not null references public.bible_journeys(id) on delete cascade,
  action_text text not null,
  due_date date,
  completed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.bible_followups (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  journey_id uuid not null references public.bible_journeys(id) on delete cascade,
  prompt text not null,
  due_at timestamptz not null,
  answered_at timestamptz,
  answer text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.bible_groups (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  tenant_slug text not null default 'ekodi-church',
  name text not null,
  kind text not null default 'small_group' check (kind in ('family','small_group','church','other')),
  invite_code text not null unique default upper(substr(replace(gen_random_uuid()::text,'-',''),1,12)),
  created_at timestamptz not null default now()
);

create table if not exists public.bible_group_members (
  group_id uuid not null references public.bible_groups(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('owner','leader','member')),
  joined_at timestamptz not null default now(),
  primary key(group_id,user_id)
);

create table if not exists public.bible_shared_journeys (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  group_id uuid not null references public.bible_groups(id) on delete cascade,
  journey_id uuid not null references public.bible_journeys(id) on delete cascade,
  note text not null default '',
  created_at timestamptz not null default now(),
  unique(group_id,journey_id)
);

create table if not exists public.bible_content_plans (
  id uuid primary key default gen_random_uuid(),
  tenant_slug text not null default 'ekodi-church',
  title text not null,
  question text not null,
  scripture_ref text not null,
  scripture_note text not null default '',
  practice_prompt text not null default '',
  active_date date not null default current_date,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create index if not exists idx_bible_journeys_user_created on public.bible_journeys(user_id, created_at desc);
create index if not exists idx_bible_conversations_user_created on public.bible_conversations(user_id, created_at desc);
create index if not exists idx_bible_messages_conversation_created on public.bible_messages(conversation_id, created_at);
create index if not exists idx_bible_followups_user_due on public.bible_followups(user_id, due_at);
create index if not exists idx_bible_practices_user_created on public.bible_practices(user_id, created_at desc);
create index if not exists idx_bible_group_members_user on public.bible_group_members(user_id, group_id);
create index if not exists idx_bible_shared_group_created on public.bible_shared_journeys(group_id, created_at desc);
create index if not exists idx_bible_content_tenant_date on public.bible_content_plans(tenant_slug, active_date desc) where is_active=true;

