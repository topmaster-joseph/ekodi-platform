export const topicById = id => TOPICS.find(topic => topic.id === id) || TOPICS[0];
export function formatFacilitatorGuide(topic) {
  return [
    '에코디 함께읽기 · 모임 진행안',
    topic.title,
    topic.subtitle,
    '읽을 자료: ' + topic.books,
    '총 ' + topic.duration + '분',
    '',
    '[진행 순서]',
    ...topic.stages.map((stage, i) => (i+1) + '. ' + stage.label + ' (' + stage.min + '분) — ' + stage.detail),
    '',
    '[토론 질문]',
    ...topic.questions.map((question, i) => (i+1) + '. ' + question),
    '',
    '[마무리]',
    '서로 다른 생각을 존중하고 실제로 할 수 있는 작은 실천을 한 가지 정합니다.',
    '자료 출처·이용 권한과 참여자의 공유 동의를 확인합니다.'
  ].join('\n');
}
