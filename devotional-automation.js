function json(data, status = 200, inheritedHeaders = new Headers()) {
  const headers = new Headers();
  headers.set('content-type', 'application/json; charset=utf-8');
  headers.set('cache-control', 'no-store');
  headers.set('x-content-type-options', 'nosniff');
  for (const name of ['access-control-allow-origin','access-control-allow-headers','access-control-allow-methods','access-control-max-age','vary']) {
    const value = inheritedHeaders.get(name);
    if (value) headers.set(name, value);
  }
  return new Response(JSON.stringify(data), { status, headers });
}

async function readJson(request) {
  try { return await request.json(); } catch { return null; }
}

export async function ensureDevotionalSchema(db) {
  const now = new Date().toISOString();
  await db.batch([
    db.prepare(`CREATE TABLE IF NOT EXISTS devotional_settings (
      id INTEGER PRIMARY KEY CHECK (id = 1),
      timezone TEXT NOT NULL DEFAULT 'Asia/Seoul',
      church_label TEXT NOT NULL DEFAULT '에코디교회',
      church_time TEXT NOT NULL DEFAULT '06:00',
      mission_label TEXT NOT NULL DEFAULT '에코디선교회',
      mission_time TEXT NOT NULL DEFAULT '07:00',
      auto_schedule INTEGER NOT NULL DEFAULT 0,
      updated_at TEXT NOT NULL
    )`),
    db.prepare(`CREATE TABLE IF NOT EXISTS devotional_entries (
      id TEXT PRIMARY KEY,
      series_id TEXT NOT NULL,
      publish_date TEXT NOT NULL,
      passage TEXT NOT NULL,
      title TEXT NOT NULL,
      script TEXT NOT NULL,
      core TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'script_ready',
      video_path TEXT NOT NULL DEFAULT '',
      church_youtube_id TEXT NOT NULL DEFAULT '',
      mission_youtube_id TEXT NOT NULL DEFAULT '',
      church_publish_at TEXT NOT NULL DEFAULT '',
      mission_publish_at TEXT NOT NULL DEFAULT '',
      error TEXT NOT NULL DEFAULT '',
      updated_at TEXT NOT NULL
    )`),
    db.prepare(`CREATE TABLE IF NOT EXISTS devotional_jobs (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      entry_id TEXT NOT NULL,
      kind TEXT NOT NULL,
      target TEXT NOT NULL DEFAULT 'master',
      status TEXT NOT NULL DEFAULT 'queued',
      payload_json TEXT NOT NULL DEFAULT '{}',
      created_at TEXT NOT NULL,
      updated_at TEXT NOT NULL
    )`),
    db.prepare('CREATE INDEX IF NOT EXISTS idx_devotional_entries_date ON devotional_entries(publish_date)'),
    db.prepare('CREATE INDEX IF NOT EXISTS idx_devotional_jobs_status ON devotional_jobs(status, created_at)')
  ]);
  await db.prepare(`INSERT OR IGNORE INTO devotional_settings
    (id, timezone, church_label, church_time, mission_label, mission_time, auto_schedule, updated_at)
    VALUES (1, ?, '에코디교회', '06:00', '에코디선교회', '07:00', 0, ?)`)
    .bind(DEFAULT_TIMEZONE, now).run();
  const seed = db.prepare(`INSERT OR IGNORE INTO devotional_entries
    (id, series_id, publish_date, passage, title, script, core, status, updated_at)
    VALUES (?, ?, ?, ?, ?, ?, ?, 'script_ready', ?)`);
  await db.batch(DEVOTIONAL_SEED.map(entry => seed.bind(
    entry.id, entry.seriesId, entry.date, entry.passage, entry.title, entry.script, entry.core, now
  )));
}

function localPublishAt(date, time, timezone) {
  return { local: `${date}T${time}:00`, timezone: timezone || DEFAULT_TIMEZONE };
}

async function overview(env) {
  await ensureDevotionalSchema(env.DB);
  const [settings, rows, jobs] = await Promise.all([
    env.DB.prepare('SELECT * FROM devotional_settings WHERE id = 1').first(),
    env.DB.prepare('SELECT * FROM devotional_entries WHERE series_id = ? ORDER BY publish_date').bind(SERIES_ID).all(),
    env.DB.prepare(`SELECT status, kind, COUNT(*) AS count FROM devotional_jobs GROUP BY status, kind`).all()
  ]);
  const entries = rows.results.map(row => ({
    id: row.id,
    seriesId: row.series_id,
    date: row.publish_date,
    passage: row.passage,
    title: row.title,
    script: row.script,
    core: row.core,
    status: row.status,
    videoPath: row.video_path,
    churchYoutubeId: row.church_youtube_id,
    missionYoutubeId: row.mission_youtube_id,
    churchPublishAt: row.church_publish_at,
    missionPublishAt: row.mission_publish_at,
    error: row.error,
    updatedAt: row.updated_at
  }));
  return {
    schemaVersion: 1,
    seriesId: SERIES_ID,
    settings: {
      timezone: settings?.timezone || DEFAULT_TIMEZONE,
      channels: {
        church: { key:'church', label:settings?.church_label || '에코디교회', time:settings?.church_time || '06:00' },
        mission: { key:'mission', label:settings?.mission_label || '에코디선교회', time:settings?.mission_time || '07:00' }
      },
      autoSchedule: Boolean(settings?.auto_schedule)
    },
    capabilities: {
      rendererConnected: Boolean(env.DEVOTIONAL_RENDERER_URL),
      publisherConnected: Boolean(env.DEVOTIONAL_PUBLISHER_URL),
      storageGateway: 'https://api.ekodi.kr/api/storage/v1',
      rendering: 'FFmpeg 1080x1920 H.264/AAC',
      publishMode: 'preupload-private-then-schedule'
    },
    summary: {
      total: entries.length,
      scriptReady: entries.filter(item => item.status === 'script_ready').length,
      renderQueued: entries.filter(item => item.status === 'render_queued').length,
      rendered: entries.filter(item => ['rendered','schedule_queued','scheduled','published'].includes(item.status)).length,
      scheduled: entries.filter(item => ['scheduled','published'].includes(item.status)).length,
      published: entries.filter(item => item.status === 'published').length
    },
    jobs: jobs.results,
    entries
  };
}

async function queueJobs(env, kind, ids = []) {
  const selected = ids.length ? new Set(ids) : null;
  const rows = await env.DB.prepare('SELECT * FROM devotional_entries WHERE series_id = ? ORDER BY publish_date').bind(SERIES_ID).all();
  const eligible = rows.results.filter(row => {
    if (selected && !selected.has(row.id)) return false;
    if (kind === 'render') return ['script_ready','render_failed'].includes(row.status);
    return ['rendered','schedule_failed'].includes(row.status);
  });
  if (!eligible.length) return { queued: 0, jobs: [] };
  const now = new Date().toISOString();
  const settings = await env.DB.prepare('SELECT * FROM devotional_settings WHERE id = 1').first();
  const insert = env.DB.prepare(`INSERT INTO devotional_jobs
    (entry_id, kind, target, status, payload_json, created_at, updated_at)
    VALUES (?, ?, ?, 'queued', ?, ?, ?)`);
  const update = env.DB.prepare('UPDATE devotional_entries SET status = ?, error = \'\', updated_at = ? WHERE id = ?');
  const statements = [];
  const jobs = [];
  for (const row of eligible) {
    const payload = kind === 'render'
      ? { entryId:row.id, date:row.publish_date, passage:row.passage, title:row.title, script:row.script, core:row.core, output:{ width:1080, height:1920, fps:30, videoCodec:'h264', audioCodec:'aac', durationTargetSeconds:30 }, variants:['church','mission'] }
      : { entryId:row.id, videoPath:row.video_path, channels:{ church:{ label:settings.church_label, publishAt:localPublishAt(row.publish_date, settings.church_time, settings.timezone) }, mission:{ label:settings.mission_label, publishAt:localPublishAt(row.publish_date, settings.mission_time, settings.timezone) } }, mode:'preupload-private-then-schedule' };
    statements.push(insert.bind(row.id, kind, kind === 'render' ? 'master' : 'both', JSON.stringify(payload), now, now));
    statements.push(update.bind(kind === 'render' ? 'render_queued' : 'schedule_queued', now, row.id));
    jobs.push(payload);
  }
  await env.DB.batch(statements);
  const endpoint = kind === 'render' ? env.DEVOTIONAL_RENDERER_URL : env.DEVOTIONAL_PUBLISHER_URL;
  const token = kind === 'render' ? env.DEVOTIONAL_RENDERER_TOKEN : env.DEVOTIONAL_PUBLISHER_TOKEN;
  let dispatched = false;
  let dispatchError = '';
  if (endpoint) {
    try {
      const headers = { 'content-type':'application/json' };
      if (token) headers.authorization = `Bearer ${token}`;
      const response = await fetch(endpoint, { method:'POST', headers, body:JSON.stringify({ seriesId:SERIES_ID, action:`${kind}_batch`, jobs }) });
      dispatched = response.ok;
      if (!response.ok) dispatchError = `HTTP ${response.status}`;
    } catch (error) {
      dispatchError = String(error?.message || 'executor dispatch failed').slice(0,180);
    }
  }
  return { queued: eligible.length, jobs, dispatched, dispatchError, executorConnected:Boolean(endpoint) };
}

export function isDevotionalControlPath(path) {
  return String(path || '').startsWith('/api/control/devotional');
}

export async function handleDevotionalControl(request, env, session, inheritedHeaders, writeAudit) {
  if (!env.DB) return json({ error:'데이터베이스 연결이 설정되지 않았습니다.' }, 503, inheritedHeaders);
  await ensureDevotionalSchema(env.DB);
  const url = new URL(request.url);
  const path = url.pathname;

  if (request.method === 'GET' && path === '/api/control/devotional/overview') {
    return json(await overview(env), 200, inheritedHeaders);
  }

  if (request.method === 'PUT' && path === '/api/control/devotional/settings') {
    const body = await readJson(request);
    const timezone = String(body?.timezone || DEFAULT_TIMEZONE).trim().slice(0,64);
    const churchLabel = String(body?.channels?.church?.label || '에코디교회').trim().slice(0,80);
    const churchTime = /^\d{2}:\d{2}$/.test(body?.channels?.church?.time || '') ? body.channels.church.time : '06:00';
    const missionLabel = String(body?.channels?.mission?.label || '에코디선교회').trim().slice(0,80);
    const missionTime = /^\d{2}:\d{2}$/.test(body?.channels?.mission?.time || '') ? body.channels.mission.time : '07:00';
    const autoSchedule = Boolean(body?.autoSchedule);
    const now = new Date().toISOString();
    await env.DB.prepare(`UPDATE devotional_settings SET timezone=?, church_label=?, church_time=?, mission_label=?, mission_time=?, auto_schedule=?, updated_at=? WHERE id=1`)
      .bind(timezone, churchLabel, churchTime, missionLabel, missionTime, autoSchedule ? 1 : 0, now).run();
    await writeAudit(env, session, 'devotional.settings.update', SERIES_ID, JSON.stringify({ timezone, churchLabel, churchTime, missionLabel, missionTime, autoSchedule }));
    return json(await overview(env), 200, inheritedHeaders);
  }

  const entryMatch = path.match(/^\/api\/control\/devotional\/entries\/(devotional-\d{4}-\d{2}-\d{2})$/);
  if (entryMatch && request.method === 'PUT') {
    const body = await readJson(request);
    const title = String(body?.title || '').trim().slice(0,160);
    const script = String(body?.script || '').trim().slice(0,2200);
    const core = String(body?.core || '').trim().slice(0,400);
    if (!title || !script || !core) return json({ error:'제목, 대본, 핵심문장을 모두 입력해 주세요.' }, 400, inheritedHeaders);
    const now = new Date().toISOString();
    await env.DB.prepare(`UPDATE devotional_entries SET title=?, script=?, core=?, status='script_ready', error='', updated_at=? WHERE id=?`)
      .bind(title, script, core, now, entryMatch[1]).run();
    await writeAudit(env, session, 'devotional.entry.update', entryMatch[1], title);
    return json(await overview(env), 200, inheritedHeaders);
  }

  if (request.method === 'POST' && path === '/api/control/devotional/prepare') {
    await writeAudit(env, session, 'devotional.prepare', SERIES_ID, 'September seed verified');
    return json(await overview(env), 200, inheritedHeaders);
  }

  if (request.method === 'POST' && path === '/api/control/devotional/render') {
    const body = await readJson(request);
    const result = await queueJobs(env, 'render', Array.isArray(body?.ids) ? body.ids : []);
    await writeAudit(env, session, 'devotional.render.queue', SERIES_ID, JSON.stringify({ queued:result.queued, dispatched:result.dispatched }));
    return json({ ok:true, ...result, overview:await overview(env) }, result.dispatchError && result.executorConnected ? 502 : 200, inheritedHeaders);
  }

  if (request.method === 'POST' && path === '/api/control/devotional/schedule') {
    const body = await readJson(request);
    const result = await queueJobs(env, 'schedule', Array.isArray(body?.ids) ? body.ids : []);
    await writeAudit(env, session, 'devotional.schedule.queue', SERIES_ID, JSON.stringify({ queued:result.queued, dispatched:result.dispatched }));
    return json({ ok:true, ...result, overview:await overview(env) }, result.dispatchError && result.executorConnected ? 502 : 200, inheritedHeaders);
  }

  return json({ error:'Devotional control endpoint not found' }, 404, inheritedHeaders);
}
