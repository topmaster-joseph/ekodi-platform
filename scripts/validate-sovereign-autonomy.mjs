import fs from 'node:fs';
import { evaluateAutonomyEnvelope } from '../sovereign-autonomy-policy.js';
const j=p=>JSON.parse(fs.readFileSync(p,'utf8').replace(/^\uFEFF/,''));
const p=j('governance/architecture/ekodi-sovereign-autonomy.json');
const c=j('governance/constitution/constitution.json');
const fail=m=>{throw new Error('Sovereign autonomy validation failed: '+m)};
for(const l of ['A0','A1','A2','A3','A4','A5'])if(!p.levels?.[l])fail('missing '+l);
if(p.sovereignAuthority!=='ekodi_platform_super_administrator')fail('human sovereign authority drift');
if(p.delegatedExecutionAuthority!=='ekodi_autonomous_control_plane')fail('delegated authority drift');
if(p.providerAgentsAreWorkersNotAuthority!==true)fail('providers/agents must not become authority');
if(!p.sovereignClasses?.includes('production_secret_change'))fail('production secret change must remain sovereign');
if(p.implicitBudgetForbidden!==true||p.costPolicy?.noNumericBudgetInferred!==true)fail('implicit budget must be forbidden');
if(p.safeRollback?.automaticForFailedA3!==true||p.safeRollback?.requiresVerification!==true)fail('A3 rollback must be automatic and verified');
if(c.sovereignAutonomy?.registry!=='governance/architecture/ekodi-sovereign-autonomy.json')fail('constitution registry mismatch');
const a3=evaluateAutonomyEnvelope({production:true,delegated:true,existingBoundary:true,reversible:true,preflightVerified:true,postVerificationRequired:true,automaticRollback:true,logged:true});
if(a3.level!=='A3'||!a3.automaticAllowed)fail('bounded production must classify A3');
if(evaluateAutonomyEnvelope({highImpact:true}).level!=='A4')fail('explicit high-impact action must be A4');
if(evaluateAutonomyEnvelope({area:'production_secret_change'}).level!=='A4')fail('production secret change must be A4');
if(evaluateAutonomyEnvelope({paidCommitment:true}).level!=='A4')fail('unbudgeted paid commitment must be A4');
if(evaluateAutonomyEnvelope({guardrailBypass:true}).level!=='A5')fail('guardrail bypass must be A5');
console.log('??Sovereign autonomy policy valid: A0-A3 automatic, A4 sovereign, A5 forbidden.');
