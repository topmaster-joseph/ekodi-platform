import fs from 'node:fs';
const fail=message=>{throw new Error(message)};
const policy=JSON.parse(fs.readFileSync(new URL('../config/write-ingress-policy.json',import.meta.url),'utf8'));
if(policy.status!=='enforced')fail('write ingress policy must be enforced');
if(policy.appliesRecursivelyToAllServices!==true)fail('write ingress policy must apply recursively');
if(policy.ingress?.productionQueueRequired!==true)fail('production durable queue is required');
if(policy.ingress?.directDatabaseWriteForbiddenForBurstEligiblePublicWrites!==true)fail('burst eligible public writes must not write DB synchronously');
if(policy.ingress?.successRequiresDurableAcceptance!==true)fail('success requires durable acceptance');
if(policy.ingress?.idempotencyKeyRequired!==true)fail('idempotency key is required');
if(policy.failure?.falseSuccessForbidden!==true)fail('false success must remain forbidden');
if(policy.consumer?.deadLetterRequired!==true)fail('dead letter queue is required');
console.log('EKODI durable write ingress policy valid.');
