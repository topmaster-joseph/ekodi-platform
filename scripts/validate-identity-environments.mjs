import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=file=>fs.readFileSync(path.join(root,file),'utf8').replace(/^\uFEFF/,'');
const json=file=>JSON.parse(read(file));
const failures=[];
const fail=message=>failures.push(message);
const identity=json('config/identity-environments.json');
const environments=json('config/ekodi-environments.json');
const constitution=json('governance/constitution/constitution.json');
const workflow=read('.github/workflows/deploy-control-api.yml');
const wrangler=read('wrangler.api.toml');
const mail=read('mail-google-adapter.js');
const drive=read('google-drive-storage-control.js');
const writer=read('canonical-drive-writer.js');
const marketing=read('marketing-growth-worker.js');
const storageWorkflow=read('.github/workflows/deploy-storage.yml');
const prod=identity.environments?.production||{};
const staging=identity.environments?.staging||{};
const dev=identity.environments?.development||{};
if(JSON.stringify(prod.authorizedJavaScriptOrigins)!==JSON.stringify(['https://ekodi.kr'])) fail('production Google JavaScript origin must be exactly https://ekodi.kr');
if(JSON.stringify(staging.authorizedJavaScriptOrigins)!==JSON.stringify(['https://staging.ekodi.kr'])) fail('staging Google JavaScript origin must be exactly https://staging.ekodi.kr');
if(!Array.isArray(dev.authorizedJavaScriptOrigins)||!dev.authorizedJavaScriptOrigins.length) fail('development origins are missing');
for(const origin of dev.authorizedJavaScriptOrigins||[]) if(!/^http:\/\/(localhost|127\.0\.0\.1):\d+$/.test(origin)) fail(`development origin must be exact localhost port: ${origin}`);
const bindings=[prod.googleClientBinding,staging.googleClientBinding,dev.googleClientBinding];
if(new Set(bindings).size!==3) fail('identity client bindings must be distinct across environments');
const namespaces=[prod.sessionNamespace,staging.sessionNamespace,dev.sessionNamespace];
if(new Set(namespaces).size!==3) fail('identity session namespaces must be distinct across environments');
if(identity.serviceOAuth?.genericIdentityClientFallbackForbidden!==true) fail('service OAuth must forbid login-client fallback');
if(identity.productionRules?.crossEnvironmentSessionReuseForbidden!==true||identity.productionRules?.crossEnvironmentSecretReuseForbidden!==true) fail('cross-environment sessions and secrets must be forbidden');
if(environments.environments?.production?.identity?.profile!=='production') fail('production environment identity profile missing');
if(environments.environments?.staging?.identity?.profile!=='staging') fail('staging environment identity profile missing');
if(environments.environments?.development?.identity?.profile!=='development') fail('development environment identity profile missing');
if(constitution.version!=='1.10.0') fail('identity isolation requires Constitution v1.10.0');
if(constitution.identityEnvironmentPolicy?.registry!=='config/identity-environments.json') fail('constitution identity registry mismatch');
if(constitution.identityEnvironmentPolicy?.serviceOAuthGenericIdentityFallbackForbidden!==true) fail('constitution must forbid service OAuth login-client fallback');
const stagingJob=workflow.match(/\n  staging:[\s\S]*?\n  production:/)?.[0]||'';
for(const marker of ['environment: staging','CLOUDFLARE_STAGING_API_TOKEN','CLOUDFLARE_STAGING_ACCOUNT_ID','GOOGLE_STAGING_CLIENT_ID','GOOGLE_IDENTITY_ORIGIN = "https://staging.ekodi.kr"','ALLOWED_ORIGINS = "https://staging.ekodi.kr"']) if(!stagingJob.includes(marker)) fail(`staging identity boundary missing: ${marker}`);
if(stagingJob.includes('483044030492-4e6231l5glchhtniroinvuq3ev6n5mv5.apps.googleusercontent.com')) fail('staging must not hardcode the production Google client');
if(!wrangler.includes('GOOGLE_IDENTITY_ORIGIN = "https://ekodi.kr"')) fail('production identity origin binding missing');
for(const [name,text] of [['mail',mail],['drive',drive],['canonical-drive-writer',writer]]) if(text.includes('|| env.GOOGLE_CLIENT_ID')) fail(`${name} service OAuth still falls back to the sign-in client`);
if(marketing.includes('env.GOOGLE_CLIENT_SECRET')||marketing.includes('env.GOOGLE_CLIENT_ID && providerSecret(env,YOUTUBE_PROVIDER)')) fail('Marketing YouTube still depends on generic Google identity credentials');
if(storageWorkflow.includes('${GOOGLE_DRIVE_CLIENT_SECRET:-${GOOGLE_CLIENT_SECRET:-}}')) fail('Storage workflow still falls back to generic Google client secret');
if(workflow.includes('${MAIL_GOOGLE_CLIENT_SECRET:-${GOOGLE_CLIENT_SECRET:-}}')) fail('Mail workflow still falls back to generic Google client secret');
if(identity.providerMigration?.productionOriginRegistration!=='pending-google-console') fail('provider-side production origin migration status must remain honest until Google Console is changed');
if(failures.length){
  console.error(`EKODI identity environment validation failed (${failures.length})`);
  failures.forEach(message=>console.error(`- ${message}`));
  process.exit(1);
}
console.log('EKODI Identity Environment Constitution: OK');
console.log('- production/staging/development Google identity boundaries are distinct');
console.log('- production JavaScript origin is exactly https://ekodi.kr');
console.log('- service OAuth no longer falls back to the Google sign-in identity client');
console.log('- provider-side Google Console migration remains explicitly pending');
