#!/usr/bin/env node
// FOOTER-TRAFFIC-GUARANTEE (static layer): every asset-first public HTML page in
// dist/ gets the shared footer visit summary, including pages added in future.
// Worker-first paths are covered at runtime by footer-traffic-guarantee.js, so
// they are left untouched here (avoids double boot next to the full Shell).
// For pages whose static CSP forbids scripts, a page-scoped CSP that allows only
// same-origin ('self' = https://ekodi.kr) scripts and telemetry is appended to
// dist/_headers. The global script-free default stays unchanged.
import {readFile, writeFile, readdir} from 'node:fs/promises';
import {join, relative, sep} from 'node:path';
import {fileURLToPath} from 'node:url';
import {injectFooterTrafficIntoHtml, htmlHasFooterTraffic, isFooterTrafficPublicPath} from '../footer-traffic-guarantee.js';

const MARK = '# FOOTER-TRAFFIC-GUARANTEE (generated by scripts/footer-traffic-postbuild.mjs)';

export function parseWorkerFirst(toml) {
  const match = String(toml || '').match(/^run_worker_first\s*=\s*\[([^\]]*)\]/m);
  if (!match) return [];
  return [...match[1].matchAll(/"([^"]+)"/g)].map(item => item[1]);
}

function globRegex(pattern) {
  const escaped = pattern.replace(/[.+?^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '.*');
  return new RegExp(`^${escaped}$`);
}

export function isWorkerFirst(urlPath, rules) {
  let hit = false;
  for (const rule of rules) {
    if (rule.startsWith('!')) { if (globRegex(rule.slice(1)).test(urlPath)) return false; continue; }
    if (globRegex(rule).test(urlPath)) hit = true;
  }
  return hit;
}

export function parseHeaderRules(text) {
  const rules = [];
  let current = null;
  for (const raw of String(text || '').split('\n')) {
    if (!raw.trim() || raw.trim().startsWith('#')) continue;
    if (!/^\s/.test(raw)) { current = {pattern: raw.trim(), detach: [], headers: []}; rules.push(current); continue; }
    if (!current) continue;
    const line = raw.trim();
    if (line.startsWith('!')) { current.detach.push(line.slice(1).trim().toLowerCase()); continue; }
    const index = line.indexOf(':');
    if (index > 0) current.headers.push([line.slice(0, index).trim().toLowerCase(), line.slice(index + 1).trim()]);
  }
  return rules;
}

export function effectiveCsp(urlPath, rules) {
  let csp = '';
  for (const rule of rules) {
    if (!globRegex(rule.pattern).test(urlPath)) continue;
    if (rule.detach.includes('content-security-policy')) csp = '';
    for (const [name, value] of rule.headers) if (name === 'content-security-policy') csp = csp ? `${csp}, ${value}` : value;
  }
  return csp;
}

function directive(csp, name) {
  const part = String(csp || '').split(';').map(value => value.trim()).find(value => value.split(/\s+/)[0].toLowerCase() === name);
  return part ? part.split(/\s+/).slice(1) : null;
}
export function cspAllowsFooterTraffic(csp) {
  if (!csp) return true;
  if (csp.includes(',')) return false; // merged policies: be explicit
  const allows = values => values && !values.includes("'none'") && (values.includes("'self'") || values.includes('https://ekodi.kr') || values.includes('https:') || values.includes('*'));
  const fallback = directive(csp, 'default-src');
  const script = directive(csp, 'script-src') || fallback;
  const connect = directive(csp, 'connect-src') || fallback;
  return Boolean(allows(script) && allows(connect));
}
export function footerTrafficPageCsp(csp) {
  const parts = String(csp || "default-src 'none'").split(';').map(value => value.trim()).filter(Boolean);
  const map = new Map(parts.map(part => [part.split(/\s+/)[0].toLowerCase(), part]));
  for (const name of ['script-src', 'connect-src']) {
    const values = (map.get(name) || name).split(/\s+/).slice(1).filter(value => value !== "'none'");
    if (!values.includes("'self'")) values.unshift("'self'");
    map.set(name, `${name} ${values.join(' ')}`);
  }
  return [...map.values()].join('; ');
}

export function urlPathsForDistFile(relPath) {
  const posix = relPath.split(sep).join('/');
  if (posix === 'index.html') return ['/'];
  if (posix.endsWith('/index.html')) { const dir = '/' + posix.slice(0, -'index.html'.length); return [dir, dir.slice(0, -1)]; }
  const page = '/' + posix;
  return [page, page.replace(/\.html$/, '')];
}

async function htmlFiles(dir) {
  const out = [];
  for (const entry of await readdir(dir, {withFileTypes: true})) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...await htmlFiles(path));
    else if (entry.name.endsWith('.html')) out.push(path);
  }
  return out;
}

export async function runFooterTrafficPostbuild({root = fileURLToPath(new URL('..', import.meta.url)), dist = 'dist', wrangler = 'wrangler.site.toml'} = {}) {
  const distDir = join(root, dist);
  const workerFirst = parseWorkerFirst(await readFile(join(root, wrangler), 'utf8'));
  const headersPath = join(distDir, '_headers');
  let headersText = '';
  try { headersText = await readFile(headersPath, 'utf8'); } catch {}
  const markIndex = headersText.indexOf(MARK);
  if (markIndex >= 0) headersText = headersText.slice(0, markIndex).trimEnd() + '\n';
  const headerRules = parseHeaderRules(headersText);
  const report = {injected: [], alreadyPresent: [], workerFirst: [], excluded: [], cspScoped: []};
  const extraHeaders = [];
  for (const file of (await htmlFiles(distDir)).sort()) {
    const rel = relative(distDir, file);
    const paths = urlPathsForDistFile(rel);
    const primary = paths[0];
    if (!paths.every(isFooterTrafficPublicPath)) { report.excluded.push(primary); continue; }
    if (paths.some(path => isWorkerFirst(path, workerFirst))) { report.workerFirst.push(primary); continue; }
    const html = await readFile(file, 'utf8');
    if (htmlHasFooterTraffic(html)) report.alreadyPresent.push(primary);
    else { await writeFile(file, injectFooterTrafficIntoHtml(html)); report.injected.push(primary); }
    // Directory pages are canonical with a trailing slash (the bare path redirects).
    for (const path of rel.endsWith('index.html') ? [primary] : paths) {
      const csp = effectiveCsp(path, headerRules);
      if (cspAllowsFooterTraffic(csp)) continue;
      extraHeaders.push(`${path}\n  ! Content-Security-Policy\n  Content-Security-Policy: ${footerTrafficPageCsp(csp.split(',')[0])}`);
      report.cspScoped.push(path);
    }
  }
  if (extraHeaders.length) headersText = `${headersText.trimEnd()}\n\n${MARK}\n${extraHeaders.join('\n\n')}\n`;
  if (headersText) await writeFile(headersPath, headersText);
  return report;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const report = await runFooterTrafficPostbuild();
  console.log(`Footer traffic guarantee: injected ${report.injected.length}, already ${report.alreadyPresent.length}, worker-first ${report.workerFirst.length}, excluded ${report.excluded.length}, page-scoped CSP ${report.cspScoped.length}`);
  for (const key of ['injected', 'cspScoped', 'excluded']) if (report[key].length) console.log(`  ${key}: ${report[key].join(' ')}`);
}
