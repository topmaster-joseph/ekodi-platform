import fs from 'node:fs';
const p=JSON.parse(fs.readFileSync(new URL('../config/concurrent-traffic-policy.json',import.meta.url),'utf8'));
const fail=(m)=>{console.error('[EKODI-CONCURRENT-TRAFFIC-10K-001] '+m);process.exitCode=1};
if(p.status!=='enforced')fail('policy must be enforced');
if(p.appliesRecursivelyToAllServices!==true)fail('all services must inherit policy');
if(p.objective?.normalConcurrentUsers!==100||p.objective?.busyConcurrentUsers!==1000||p.objective?.surgeConcurrentUsers!==10000)fail('100/1000/10000 tiers required');
if(p.objective?.publicDatabaseBypassTargetPercent<95)fail('public DB bypass target must be >=95%');
if(p.promotion?.doNotUseConcurrencyAlone!==true)fail('concurrency alone must not trigger promotion');
if(p.recovery?.hysteresisRequired!==true)fail('recovery hysteresis required');
if(p.media?.canonicalOriginal!=='google_drive')fail('Drive must remain canonical media original');
if(p.media?.databaseStoresBytes!==false)fail('database must not store media bytes');
if(p.media?.driveHotPathApiCallsForbidden!==true)fail('Drive API hot-path calls forbidden');
if(p.failurePolicy?.circuitBreaker!==true)fail('circuit breaker required');
if(!process.exitCode)console.log('EKODI-CONCURRENT-TRAFFIC-10K-001 validated.');
